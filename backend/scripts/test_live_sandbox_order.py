import sys
import json
import urllib.request
import urllib.error

def request_json(url, method='GET', data=None, headers=None):
    if headers is None:
        headers = {}
    req_data = None
    if data is not None:
        req_data = json.dumps(data).encode('utf-8')
        headers['Content-Type'] = 'application/json'
    
    req = urllib.request.Request(url, data=req_data, headers=headers, method=method)
    try:
        with urllib.request.urlopen(req) as resp:
            body = resp.read().decode('utf-8')
            return resp.status, json.loads(body)
    except urllib.error.HTTPError as e:
        body = e.read().decode('utf-8')
        try:
            return e.code, json.loads(body)
        except Exception:
            return e.code, body

def test_live_order():
    # 1. Fetch available products and find in-stock variant
    status, products = request_json('http://127.0.0.1:8000/products')
    if status != 200:
        print(f"Failed to fetch products: {status} {products}")
        return False
    
    if not products:
        print("No products found in test DB!")
        return False

    chosen_p = None
    chosen_variant = None
    for p in products:
        for v in p.get('variants', []):
            if v.get('is_active', True) and v.get('stock', 0) > 0:
                chosen_p = p
                chosen_variant = v
                break
        if chosen_variant:
            break

    if not chosen_variant:
        print("No in-stock active variants found!")
        return False

    p = chosen_p
    variant = chosen_variant
    prod_name = p.get('name') or p.get('title')
    var_size = variant.get('size') or variant.get('name')
    price = variant.get('price') or p.get('price')
    print(f"Product Selected: '{prod_name}' | Variant: '{var_size}' (ID: {variant['id']}, Stock: {variant['stock']}) | Price: Rs.{price}")

    # 2. Place a PREPAID order
    order_payload = {
        'customer_name': 'Aarav Sharma',
        'phone': '+91 98765 43210',
        'payment_method': 'PREPAID',
        'items': [
            {
                'variant_id': variant['id'],
                'quantity': 1
            }
        ],
        'address': {
            'name': 'Aarav Sharma',
            'phone': '9876543210',
            'pincode': '400001',
            'line1': 'Flat 402, Royal Palms, MG Road',
            'city': 'Mumbai',
            'state': 'Maharashtra'
        }
    }

    status, order_data = request_json('http://127.0.0.1:8000/orders', method='POST', data=order_payload)
    if status != 201:
        print(f"Failed to create order: {status} - {order_data}")
        return False
        
    order_code = order_data['order_code']
    order_token = order_data['order_token']
    total = order_data['total']
    print(f"[OK] Order created in local test DB: Code={order_code}, Total=Rs.{total}")

    # 3. Call Cashfree create-order endpoint (Communicates directly with Cashfree Sandbox API)
    print("\nCalling Cashfree Sandbox API (https://sandbox.cashfree.com/pg/orders)...")
    status, cf_data = request_json(
        'http://127.0.0.1:8000/payments/cashfree/create-order',
        method='POST',
        data={'order_code': order_code},
        headers={'X-Order-Token': order_token}
    )
    if status != 200:
        print(f"Failed to create Cashfree session: {status} - {cf_data}")
        return False
        
    cf_order_id = cf_data.get('cf_order_id')
    payment_session_id = cf_data.get('payment_session_id')
    order_status = cf_data.get('order_status')
    
    print(f"[OK] Cashfree Sandbox Gateway Response:")
    print(f"     Cashfree Order ID: {cf_order_id}")
    print(f"     Payment Session ID: {payment_session_id[:28]}... (Valid session generated by Cashfree Sandbox)")
    print(f"     Gateway Status: {order_status}")
    
    # 4. Verify order in DB is still PENDING (not fraudulently marked paid)
    status, chk_data = request_json(f'http://127.0.0.1:8000/orders/{order_code}?token={order_token}')
    print(f"[OK] Order Payment Status in DB: {chk_data['payment_status']} (Correct: Stays PENDING until verified)")

    # 5. Check payment sync endpoint when payment has not been completed yet
    status, sync_data = request_json(
        f'http://127.0.0.1:8000/payments/cashfree/sync/{order_code}',
        method='POST',
        headers={'X-Order-Token': order_token}
    )
    print(f"[OK] Sync Payment Status (Pre-payment): {sync_data.get('payment_status')} (Verified with Cashfree: Not yet paid)")
    
    print("\n=======================================================")
    print("SUCCESS: Live Cashfree Sandbox integration is fully operational!")
    print(f"Test Order Code: {order_code}")
    print(f"Test Order Token: {order_token}")
    print(f"Storefront Return Page: http://localhost:5173/order-success/{order_code}?token={order_token}")
    print("=======================================================")
    return True

if __name__ == '__main__':
    success = test_live_order()
    sys.exit(0 if success else 1)
